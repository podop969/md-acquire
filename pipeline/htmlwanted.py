"""Render wanted.md's manual handoff as a clickable HTML page.

Reads library/wanted.md (the pipeline's own output) and writes wanted.html
beside it: one card per work, one button per source link, grouped by source.
Standalone file - no CSS framework, no scripts, dark reader-friendly.
"""
from __future__ import annotations

import html
import re
from pathlib import Path

_URL_RE = re.compile(r"https?://[^\s<>'\"]+")

_SPEC_LINE = re.compile(r"^- spec file: (.+)$")
_DETAIL_LINE = re.compile(r"^- detail: (.+)$")
_HINT_LINE = re.compile(r"^- (Open Library has a .+)$")
_LINK_LINE = re.compile(r"^  - \[(.+?)\]\((\S+?)\)\s*$")
_HEAD_RE = re.compile(r"^## (.+)$")
_META_RE = re.compile(r"^-( (?:authors|ISBN-13|DOI|year window): .+)$")


def parse_wanted(text: str) -> list[dict]:
    works: list[dict] = []
    cur: dict | None = None
    for line in text.splitlines():
        m = _HEAD_RE.match(line)
        if m:
            cur = {"title": m.group(1).strip(), "meta": [], "links": [], "detail": "", "spec": ""}
            works.append(cur)
            continue
        if cur is None:
            continue
        lm = _LINK_LINE.match(line)
        if lm:
            cur["links"].append((lm.group(1), lm.group(2)))
            continue
        if line.startswith("- search manually"):
            continue
        dm = _DETAIL_LINE.match(line)
        if dm:
            cur["detail"] = dm.group(1)
            continue
        sm = _SPEC_LINE.match(line)
        if sm:
            cur["spec"] = sm.group(1)
            continue
        hm = _HINT_LINE.match(line)
        if hm:
            cur["meta"].append(hm.group(1))
            continue
        mm = _META_RE.match(line)
        if mm:
            cur["meta"].append(mm.group(1).lstrip("- ").strip())
    return [w for w in works if w["links"] or w["meta"] or w["detail"]]


